package hub

import (
	"encoding/json"
	"fmt"
	"net"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/portcullis/hub/internal/fsutil"
	"github.com/portcullis/hub/internal/policy"
	"github.com/portcullis/hub/internal/templates"
)

// generateOverrideLocked writes the per-app compose override: user volume
// mounts, port bindings, per-router Traefik tls.options labels driven by
// the app's auth policy, and the public-exception router when it is on. Port ranges and network_mode: host ports stay in the
// base compose.yml. Caller must hold mu.
func (h *Hub) generateOverrideLocked(t *templates.Template, values map[string]string) error {
	overridePath := h.overridePath(t.ID)
	serviceMounts := make(map[string][]string)
	for _, s := range t.Manifest.Settings {
		val := values[s.Key]
		if val == "" || s.Target == nil || s.Target.Mount == "" || s.Type != "path" {
			continue
		}
		if err := templates.ValidatePathSetting(val); err != nil {
			return fmt.Errorf("setting %s: %w", s.Key, err)
		}
		// JSON string == valid YAML double-quoted scalar: safe for spaces,
		// quotes and '#'.
		mountJSON, _ := json.Marshal(val + ":" + s.Target.Mount)
		serviceMounts[s.Target.Service] = append(serviceMounts[s.Target.Service], string(mountJSON))
	}

	servicePorts := make(map[string][]string)
	for _, p := range t.Manifest.Ports {
		if p.Service == "" || p.NetworkModeHost || p.Range != "" {
			continue
		}
		proto := strings.ToLower(p.Protocol)
		if proto == "" {
			proto = "tcp"
		}
		bind := p.Bind
		if v, ok := values[p.Key+"_BIND"]; ok && v != "" {
			bind = v
		}
		if bind == "" {
			bind = "0.0.0.0"
		}
		if net.ParseIP(bind) == nil {
			return fmt.Errorf("port %s: bind %q is not an IP address", p.Key, bind)
		}
		host := p.Default
		if v, ok := values[p.Key]; ok {
			if v == "" && !p.Required {
				continue
			}
			if n, err := strconv.Atoi(v); err == nil && n > 0 {
				host = n
			}
		}
		if host <= 0 || p.Container <= 0 {
			continue
		}
		hostIP := bind
		if strings.Contains(bind, ":") { // IPv6 needs brackets
			hostIP = "[" + bind + "]"
		}
		servicePorts[p.Service] = append(servicePorts[p.Service], fmt.Sprintf("\"%s:%d:%d/%s\"", hostIP, host, p.Container, proto))
	}

	routes, err := templates.ParseRoutes(t.ReadCompose())
	if err != nil {
		return err
	}
	serviceRouters := routes.Routers
	// Public exceptions: plan from the compose file being deployed, not
	// the catalog copy (Expert edits).
	plan, err := templates.PlanPublic(&t.Manifest, routes)
	if err != nil {
		return err
	}
	pub := h.publicLocked(t, plan)
	// One tier for every router of the app's hosts (policy.HostTier).
	tier := policy.HostTier(h.st.ResolvePolicy(t.ID), pub.Active())
	var publicLines []string
	if pub.Active() {
		if publicLines, err = publicLabels(t.ID, &t.Manifest, plan, pub.Routed, tier); err != nil {
			return err
		}
	}

	services := map[string]bool{}
	for svc := range serviceMounts {
		services[svc] = true
	}
	for svc := range servicePorts {
		services[svc] = true
	}
	for svc := range serviceRouters {
		services[svc] = true
	}
	if len(services) == 0 {
		os.Remove(overridePath)
		return nil
	}
	names := make([]string, 0, len(services))
	for svc := range services {
		names = append(names, svc)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("# Auto-generated by Portcullis Hub -- do not edit\nservices:\n")
	for _, svc := range names {
		fmt.Fprintf(&b, "  %s:\n", svc)
		if mounts := serviceMounts[svc]; len(mounts) > 0 {
			b.WriteString("    volumes:\n")
			for _, m := range mounts {
				fmt.Fprintf(&b, "      - %s\n", m)
			}
		}
		if ports := servicePorts[svc]; len(ports) > 0 {
			b.WriteString("    ports:\n")
			for _, p := range ports {
				fmt.Fprintf(&b, "      - %s\n", p)
			}
		}
		if routers := serviceRouters[svc]; len(routers) > 0 {
			b.WriteString("    labels:\n")
			for _, r := range routers {
				fmt.Fprintf(&b, "      traefik.http.routers.%s.tls.options: %s\n", r, tier)
			}
			if plan != nil && svc == plan.Service {
				for _, l := range publicLines {
					fmt.Fprintf(&b, "      %s\n", l)
				}
			}
		}
	}
	return fsutil.WriteFileAtomic(overridePath, []byte(b.String()), 0600)
}
