// randomSecret returns 32 hex characters.
func randomSecret() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// generateAppEnvLocked writes the per-app .env: existing values are kept,
// missing manifest env vars are generated, the instance options' env
// deliveries are written from state (optionEnvLocked: every option env
// name, empty when unset), and ${VAR} references in compose.yml are
// filled from the core .env. Caller must hold mu.
func (h *Hub) generateAppEnvLocked(t *templates.Template, m *directory.Membership) error {
	envFile := h.envPath(t.ID)
	vars := readEnvRaw(envFile) // preserve user edits, as written
	vars["PORTCULLIS_DOMAIN"] = h.cfg.Domain

	for _, v := range t.Manifest.Env {
		if _, exists := vars[v.Key]; exists {
			continue
		}
		switch v.Generate {
		case "random":
			s, err := randomSecret()
			if err != nil {
				return err
			}
			vars[v.Key] = s
		default:
			vars[v.Key] = ""
		}
	}
	for k, v := range h.portEnvLocked(t) {
		vars[k] = v
	}
	optEnv, err := h.optionEnvLocked(t, m)
	if err != nil {
		return err
	}
	for k, v := range optEnv {
		vars[k] = v
	}
	// The instance variables (contract §2, §3.1) are derived, never kept
	// from an earlier file: hostnames and names follow the instance.
	for k, v := range t.InstanceEnv {
		vars[k] = v
	}
	for k, v := range h.aiEnvLocked(t) {
		vars[k] = v
	}
	// The mail sender variables (§19.14): derived, never kept (none at
	// all without mail_sender or on Kubernetes).
	for k := range vars {
		if strings.HasPrefix(k, templates.VarMailSenderPrefix) {
			delete(vars, k)
		}
	}
	sendEnv := h.senderEnvForLocked(t)
	for k, v := range sendEnv {
		vars[k] = v
	}
	// The model provider variables (§15.12, Task 23): exactly an AI page's
	// selected, set secrets (single-quoted); never a stale or foreign one.
	provEnv, err := h.providerEnvLocked(t)
	if err != nil {
		return err
	}
	for k := range vars {
		if strings.HasPrefix(k, ProviderVarPrefix) {
			delete(vars, k)
		}
	}
	for k, v := range provEnv {
		vars[k] = v
	}
	coreEnv := readEnvRaw(filepath.Join(h.cfg.ProjectDir, ".env"))
	for ref := range templates.EnvRefs(string(t.ReadCompose())) {
		// Core-only: not a template variable (contract §2), the whole
		// PORTCULLIS_MAIL prefix included.
		if coreOnlyVar(ref) {
			continue
		}
		if _, exists := vars[ref]; !exists {
			if v, ok := coreEnv[ref]; ok {
				vars[ref] = v
			}
		}
	}

	lines := []string{
		"# Auto-generated by Portcullis Hub — do not edit manually",
		fmt.Sprintf("# App: %s", t.Manifest.Name),
	}
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		_, quoted := optEnv[k]
		_, prov := provEnv[k]
		_, snd := sendEnv[k]
		lines = append(lines, envLine(k, vars[k], quoted || prov || snd))
	}
	// The admin's env overrides last (§11.9): they win.
	block, err := h.envOverrideBlockLocked(t)
	if err != nil {
		return err
	}
	lines = append(lines, block...)
	// 0600: contains generated secrets.
	return fsutil.WriteFileAtomic(envFile, []byte(strings.Join(lines, "\n")+"\n"), 0600)
}

// writeOptionEnvLocked updates the option variables (optionEnvLocked,
// single-quoted) and the port variables (portEnvLocked) in id's .env,
// keeping every other line, then the env overrides (re-checked). Caller
// must hold mu.
func (h *Hub) writeOptionEnvLocked(t *templates.Template, m *directory.Membership) error {
	vars, err := h.optionEnvLocked(t, m)
	if err != nil {
		return err
	}
	if err := setEnvVars(h.envPath(t.ID), h.portEnvLocked(t), false); err != nil {
		return err
	}
	if err := setEnvVars(h.envPath(t.ID), vars, true); err != nil {
		return err
	}
	return h.writeEnvOverridesLocked(t)
}

// portEnvLocked are t's port settings as env variables: the stored port
// keys and <KEY>_BIND as they are, and the effective value of every port
// the app binds itself (network_mode: host, ranges: compose publishes
// nothing for them, the template reads them from the env). Caller must
// hold mu.
func (h *Hub) portEnvLocked(t *templates.Template) map[string]string {
	s := h.st.Settings[t.ID]
	out := maps.Clone(s.Ports)
	if out == nil {
		out = map[string]string{}
	}
	for k, v := range hostNetPortValues(t, s.Ports) {
		out[k] = v
	}
	return out
}

// optionEnvLocked is what the Hub writes for t's options into its .env
// (unquoted values; the writers single-quote them): every env name of an
// instance option, rendered per delivery (RenderDelivery; an indexed
// NAME_{n} one item per variable, unused ones empty), empty when the
// option has no value. A secret option's value comes from the secrets
// store (empty when unset or cleared). Left alone (P12): group-scope
// options (their records) and person-entered lists (the delivery engine
// writes those outside mu). A stored value one env delivery can't carry
// (a template update added the delivery; save refuses such values) fails
// closed for that delivery's variables only: written empty, logged and
// reported in the panel's deliveries (unit env:values); the error is
// only the secrets store being unreadable. Errors and problems never
// carry a value. The shared-folder variables (folderEnvLocked) come
// last. Caller must hold mu.
func (h *Hub) optionEnvIn(rv renderView, t *templates.Template, m *directory.Membership) (map[string]string, []string, error) {
	s := rv.settings[t.ID]
	out := map[string]string{}
	var problems []string
	var secrets map[string]string
	opts := t.Manifest.Options()
	put := func(o *templates.Option, redact []string, render func(d *templates.Delivery) (map[string]string, error)) {
		for _, d := range envDeliveries(o) {
			env, err := render(&d)
			if err != nil {
				for _, n := range envDeliveryNames(o, &d) {
					out[n] = ""
				}
				problems = append(problems, fmt.Sprintf("setting %s: %s: written empty", o.Key, redactValues(err.Error(), redact)))
				continue
			}
			for k, x := range env {
				out[k] = x
			}
		}
	}
	for i := range opts {
		o := &opts[i]
		if o.EffectiveScope() == templates.ScopeGroup && len(envDeliveries(o)) > 0 {
			// The records as one JSON value per env delivery: only
			// records of the stored type whose group id matches the
			// caller's directory snapshot m (fetched outside mu); no
			// snapshot = no records (fail closed).
			var recs []settings.Row
			if h.typeMatchesLocked(t, o.Key, o) {
				recs = h.groupRecordsOut(t, o, s.Groups[o.Key], m)
			}
			put(o, nil, func(d *templates.Delivery) (map[string]string, error) {
				return renderGroupEnvDelivery(o, recs, d)
			})
			continue
		}
		if o.EffectiveScope() != templates.ScopeInstance {
			continue
		}
		if o.Type == templates.TypeSecret {
			if len(envDeliveries(o)) == 0 {
				continue
			}
			if secrets == nil {
				var err error
				if secrets, err = h.secretValues(t.ID); err != nil {
					return nil, nil, err
				}
			}
			var v any
			if x := secrets[o.Key]; x != "" {
				if _, set := s.Secrets[o.Key]; set {
					v = x
				}
			}
			put(o, []string{secrets[o.Key]}, func(d *templates.Delivery) (map[string]string, error) {
				return renderEnvDelivery(o, v, d)
			})
			continue
		}
		v, ok := h.effectiveValue(t, o, s)
		if !ok {
			v = nil
		}
		if str, isStr := v.(string); isStr && o.Type == templates.TypePath && strings.HasPrefix(str, folderPrefix) {
			// A folder value's env delivery carries its host path (the
			// kind never resolves a ref).
			if host, err := folderHostPath(h.folders, str); err == nil {
				v = host
			} else {
				v = nil
			}
		}
		put(o, nil, func(d *templates.Delivery) (map[string]string, error) {
			return renderEnvDelivery(o, v, d)
		})
	}
	// A gid reference holding a folder group's gid no assignment wrote
	// (ruling 30) is written empty: such a gid would reach the app.
	for _, key := range h.gidRangeProblemsIn(rv, t, s) {
		o := optionByKey(t, key)
		for _, n := range o.EnvNames() {
			out[n] = ""
		}
		problems = append(problems, fmt.Sprintf("setting %s: %s: written empty", key, errGIDReserved))
	}
	// Last (ruling 11): the folder variables, and a gid_env join's
	// variable set to the folder gid over the option's own value.
	for k, v := range h.folderEnvIn(rv, t) {
		out[k] = v
	}
	// The Local networks (F35, §3.1): every .env write carries them, the
	// canonical prefixes comma-joined ('' = saved empty: loopback only).
	out[templates.VarLocalNetworks] = h.localNetworksEnvForLocked(t.ID)
	// The setup choices' compose profiles (§13.18): Hub-set, every .env
	// write of a template with profiled services carries them ('' =
	// none). A template without any has nothing a profile could start:
	// its .env stays as it was (a manifest can't declare the variable).
	if len(t.ProfiledServices) > 0 {
		out[templates.VarComposeProfiles] = h.composeProfilesEnv(t, s)
	}
	return out, problems, nil
}

// localNetworksEnvLocked is PORTCULLIS_LOCAL_NETWORKS' value. Caller
// holds mu (read).
func (h *Hub) localNetworksEnvLocked() string { return joinPrefixes(h.localNetworksLocked()) }

// localNetworksEnvForLocked is instance id's Local networks (§14.7): a
// placed instance's are its server's setting, else the Hub's default
// list (DefaultLocalNetworks; never the primary's own setting). Caller
// holds mu.
func (h *Hub) localNetworksEnvForLocked(id string) string {
	// The server its render is for (an undo's override included).
	server := h.serverOf(id)
	if server == "" {
		return h.localNetworksEnvLocked()
	}
	cidrs := DefaultLocalNetworks
	if s, ok := h.st.Servers[server]; ok && s.LocalNetworks != nil {
		cidrs = *s.LocalNetworks
	}
	nets, err := state.ParseLocalNetworks(cidrs)
	if err != nil {
		return "" // fail closed: loopback only
	}
	return joinPrefixes(nets)
}

func joinPrefixes(nets []netip.Prefix) string {
	parts := make([]string, len(nets))
	for i, p := range nets {
		parts[i] = p.String()
	}
	return strings.Join(parts, ",")
}

// optionEnvLocked is optionEnvIn over the Hub's state; its problems are
// recorded for the panel (setEnvProblems). Caller must hold mu.
func (h *Hub) optionEnvLocked(t *templates.Template, m *directory.Membership) (map[string]string, error) {
	out, problems, err := h.optionEnvIn(h.liveView(), t, m)
	if err != nil {
		return nil, err
	}
	h.setEnvProblems(t.ID, problems)
	return out, nil
}

// envDeliveryNames are the variables env delivery d of o writes (an
// indexed NAME_{n}: each NAME_<i>).
func envDeliveryNames(o *templates.Option, d *templates.Delivery) []string {
	prefix, ok := strings.CutSuffix(d.Env, templates.IndexSuffix)
	if !ok {
		return []string{d.Env}
	}
	var out []string
	for _, n := range o.EnvNames() {
		if strings.HasPrefix(n, prefix+"_") {
			out = append(out, n)
		}
	}
	return out
}

// setEnvProblems records instance id's option env values written empty
// (optionEnvLocked), logging each new one once.
func (h *Hub) setEnvProblems(id string, problems []string) {
	sort.Strings(problems)
	h.envProblemsMu.Lock()
	defer h.envProblemsMu.Unlock()
	prev := h.envProblems[id]
	if strings.Join(prev, "\n") == strings.Join(problems, "\n") {
		return
	}
	for _, p := range problems {
		if !slices.Contains(prev, p) {
			log.Printf("settings: %s: WARNING: %s (the value can't go in the .env)", id, p)
		}
	}
	if h.envProblems == nil {
		h.envProblems = map[string][]string{}
	}
	if len(problems) == 0 {
		delete(h.envProblems, id)
		return
	}
	h.envProblems[id] = problems
}

// envProblemsUnit is the env:values unit the panel shows while some
// option env value is written empty or a stored env override is skipped
// (ok: there is one).
func (h *Hub) envProblemsUnit(id string) (UnitResult, bool) {
	h.envProblemsMu.Lock()
	defer h.envProblemsMu.Unlock()
	// The skipped env overrides (§11.9) show here too.
	p := append(slices.Clone(h.envProblems[id]), h.envDrops[id]...)
	if len(p) == 0 {
		return UnitResult{}, false
	}
	return UnitResult{Unit: unitEnvValues, Error: clipRunes(strings.Join(p, "; "), unitErrorMax)}, true
}

// envDeliveries are o's env deliveries: the declared ones, or the
// implicit env UPPER(key) of an instance option without deliveries.
func envDeliveries(o *templates.Option) []templates.Delivery {
	if len(o.Delivery) == 0 {
		if n := o.EnvName(); n != "" {
			return []templates.Delivery{{Env: n}}
		}
		return nil
	}
	var out []templates.Delivery
	for _, d := range o.Delivery {
		if d.Env != "" {
			out = append(out, d)
		}
	}
	return out
}

// renderOptionEnv renders the canonical v (nil = no value: every name
// empty) for each of o's env deliveries. A rendered value env can't
// carry single-quoted (a ' or a newline) is an error naming the variable.
func renderOptionEnv(o *templates.Option, v any) (map[string]string, error) {
	out := map[string]string{}
	for _, d := range envDeliveries(o) {
		env, err := renderEnvDelivery(o, v, &d)
		if err != nil {
			return nil, err
		}
		for k, x := range env {
			out[k] = x
		}
	}
	return out, nil
}

// renderEnvDelivery is renderOptionEnv for one env delivery d.
func renderEnvDelivery(o *templates.Option, v any, d *templates.Delivery) (map[string]string, error) {
	out := map[string]string{}
	if prefix, ok := strings.CutSuffix(d.Env, templates.IndexSuffix); ok {
		var items []string
		if v != nil {
			var err error
			if items, err = settings.RenderIndexed(o, v, d); err != nil {
				return nil, err
			}
		}
		for _, n := range o.EnvNames() {
			if !strings.HasPrefix(n, prefix+"_") {
				continue
			}
			i, _ := strconv.Atoi(strings.TrimPrefix(n, prefix+"_"))
			x := ""
			if i >= 1 && i <= len(items) {
				x = items[i-1]
			}
			if _, err := envQuote(x); err != nil {
				return nil, fmt.Errorf("env %s: %w", n, err)
			}
			out[n] = x
		}
		return out, nil
	}
	x := ""
	if v != nil {
		r, err := settings.RenderDelivery(o, v, d)
		if err != nil {
			return nil, err
		}
		x = r.Text
	}
	if err := settings.CheckEnvText(x, settings.EnvJSON(o, d)); err != nil {
		return nil, fmt.Errorf("env %s: %w", d.Env, err)
	}
	out[d.Env] = x
	return out, nil
}

// envQuote single-quotes v for an .env file: compose reads a
// single-quoted value literally ($, #, spaces and " stay as they are). A
// value with ', a backslash (compose's dotenv reads \' inside single
// quotes as an escaped quote: a trailing \ would swallow the next line)
// or a line break can't be single-quoted safely: an error.
func envQuote(v string) (string, error) {
	if err := settings.CheckEnvText(v, false); err != nil {
		return "", err
	}
	return "'" + v + "'", nil
}

// envLine is one KEY=VALUE line. A Hub-written option value (quote) is
// single-quoted (envQuote, contract §13.5; empty is KEY=); any other
// value is raw text written exactly as given — what compose reads from
// it (inline comments, $$, double quotes, interpolation) is unchanged.
// An option value that can't be quoted never reaches here (refused at
// save); it is written empty rather than unquoted.
func envLine(k, v string, quote bool) string {
	if !quote || v == "" {
		return k + "=" + v
	}
	q, err := envQuote(v)
	if err != nil {
		return k + "="
	}
	return k + "=" + q
}

// envUnquote is a value as the Hub reads it: the content of a value the
// Hub single-quoted (no ' or \ inside), anything else as written.
func envUnquote(v string) string {
	if len(v) >= 2 && v[0] == '\'' && v[len(v)-1] == '\'' && !strings.ContainsAny(v[1:len(v)-1], "'\\") {
		return v[1 : len(v)-1]
	}
	return v
}

// readEnvFile parses KEY=VALUE lines (missing file = empty map); values
// the Hub single-quoted are unquoted (envUnquote).
func readEnvFile(path string) map[string]string {
	out := readEnvRaw(path)
	for k, v := range out {
		out[k] = envUnquote(v)
	}
	return out
}

// readEnvRaw is readEnvFile with every value's raw text (what writers
// write back unchanged).
func readEnvRaw(path string) map[string]string {
	data, err := os.ReadFile(path)
	if err != nil {
		return map[string]string{}
	}
	return parseEnvRaw(data)
}

// parseEnv parses KEY=VALUE lines, unquoting values the Hub
// single-quoted.
func parseEnv(data []byte) map[string]string {
	out := parseEnvRaw(data)
	for k, v := range out {
		out[k] = envUnquote(v)
	}
	return out
}

// parseEnvRaw parses KEY=VALUE lines, values as written. The env
// overrides' block (envOverrideMarker and every line after it) is not
// read: every reader sees the values without the admin's overrides (the
// defaults, §11.9), and every writer writes the block again from state.
func parseEnvRaw(data []byte) map[string]string {
	result := make(map[string]string)
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == envOverrideMarker {
			break
		}
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, v, ok := strings.Cut(line, "="); ok {
			result[k] = v
		}
	}
	return result
}

// writeEnvMap writes vars (raw text) as a sorted KEY=VALUE file (0600:
// secrets).
func writeEnvMap(path string, vars map[string]string) error {
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("# Auto-generated by Portcullis Hub — do not edit manually\n")
	for _, k := range keys {
		b.WriteString(envLine(k, vars[k], false) + "\n")
	}
	return fsutil.WriteFileAtomic(path, []byte(b.String()), 0600)
}

// setEnvVar updates or appends key=value (raw text) in an .env file.
func setEnvVar(envFile, key, value string) error {
	return setEnvVars(envFile, map[string]string{key: value}, false)
}

// setEnvVars updates or appends each key=value (envLine; quote: Hub
// option values, single-quoted; else raw text) in an .env file in one
// write, keeping every other line as it is; new keys are appended
// sorted.
func setEnvVars(envFile string, vars map[string]string, quote bool) error {
	if len(vars) == 0 {
		return nil
	}
	data, err := os.ReadFile(envFile)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	var lines []string
	if len(data) > 0 {
		lines = strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
	}
	// The env overrides' block stays last, untouched (its writer is
	// writeEnvOverridesLocked).
	lines, block := splitEnvOverrides(lines)
	done := map[string]bool{}
	for i, line := range lines {
		k, _, ok := strings.Cut(strings.TrimSpace(line), "=")
		if !ok || strings.HasPrefix(k, "#") {
			continue
		}
		// Every line of a duplicated key (compose reads the last one).
		if v, want := vars[k]; want {
			lines[i] = envLine(k, v, quote)
			done[k] = true
		}
	}
	keys := make([]string, 0, len(vars))
	for k := range vars {
		if !done[k] {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	for _, k := range keys {
		lines = append(lines, envLine(k, vars[k], quote))
	}
	lines = append(lines, block...)
	return fsutil.WriteFileAtomic(envFile, []byte(strings.Join(lines, "\n")+"\n"), 0600)
}

// hostNetPortValues are the effective values of the ports an app binds
// itself (network_mode: host or a range): compose publishes nothing for
// them, the template reads them from the env.
func hostNetPortValues(t *templates.Template, values map[string]string) map[string]string {
	out := map[string]string{}
	for _, p := range t.Manifest.Ports {
		if !p.NetworkModeHost && p.Range == "" {
			continue
		}
		v, ok := values[p.Key]
		switch {
		case ok && v != "":
			out[p.Key] = v
		case ok && !p.Required:
			out[p.Key] = ""
		case p.Range != "":
			out[p.Key] = p.Range
		case p.Default > 0:
			out[p.Key] = fmt.Sprint(p.Default)
		}
	}
	return out
}

// refreshInstanceEnvLocked rewrites the derived variables (domain and
// instance variables) and the settings' variables (optionEnvLocked) in
// an existing .env before every compose up, so the routed hostnames are
// always the Hub's and the app starts with the stored settings. Caller
// must hold mu.
func (h *Hub) refreshInstanceEnvLocked(t *templates.Template, m *directory.Membership) error {
	path := h.envPath(t.ID)
	if _, err := os.Stat(path); err != nil {
		return nil // not generated yet: enable writes it whole
	}
	cur := readEnvRaw(path)
	opts, err := h.optionEnvLocked(t, m)
	if err != nil {
		return err
	}
	want := h.portEnvLocked(t)
	want["PORTCULLIS_DOMAIN"] = h.cfg.Domain
	for k, v := range t.InstanceEnv {
		want[k] = v
	}
	for k, v := range h.aiEnvLocked(t) {
		want[k] = v
	}
	for k, v := range want {
		if c, ok := cur[k]; ok && c == v {
			delete(want, k)
		}
	}
	for k, v := range opts {
		if c, ok := cur[k]; ok && strings.TrimPrefix(envLine(k, v, true), k+"=") == c {
			delete(opts, k)
		}
	}
	if err := setEnvVars(path, want, false); err != nil {
		return err
	}
	if err := setEnvVars(path, opts, true); err != nil {
		return err
	}
	// The mail sender variables (§19.14): exactly senderEnvForLocked's
	// (single-quoted); every other PORTCULLIS_MAIL_SENDER_* line dropped.
	if err := rewriteEnvPrefix(path, templates.VarMailSenderPrefix, h.senderEnvForLocked(t)); err != nil {
		return err
	}
	// The model provider variables of the instance's own selection (a
	// restore rewrites them from the store: G30(b)).
	return h.syncProviderEnvLocked(t)
}

// aiEnvLocked are the AI variables of an ai.mcp template's instance
// (contract §3.1, G42): PORTCULLIS_AI_ENABLED true while one of its
// companions is switched on (one owing a revoke_all counts as off),
// PORTCULLIS_AI_READONLY_<C> true unless C is on in read_write — all off
// while the master switch is off or the effective policy is at LoA 3
// (aiOnLocked) —, and
// core's PORTCULLIS_MCP_GATE_IP (gateIPLocked). nil for every other
// template. Caller holds mu.
func (h *Hub) aiEnvLocked(t *templates.Template) map[string]string {
	if !t.HasAIMCP() {
		return nil
	}
	sw := h.st.AIInstances[t.ID].Companions
	out := map[string]string{templates.VarAIEnabled: "false"}
	// Master switch off or LoA 3: off in the app too (12b), whatever the
	// companions' switches say.
	on := h.aiOnLocked(t)
	for _, c := range t.Manifest.AI.MCP {
		s := sw[c.Name]
		ro := "true"
		if on && s.Enabled && !s.RevokePending {
			out[templates.VarAIEnabled] = "true"
			if s.Mode == templates.AIReadWrite {
				ro = "false"
			}
		}
		out[templates.ReadOnlyVar(c.Name)] = ro
	}
	if ip := h.gateIP(); ip != "" {
		out[templates.VarMCPGateIP] = ip
	}
	return out
}

// gateIP is core's PORTCULLIS_MCP_GATE_IP from the core env subset the
// Hub reads (secrets/hub/core.env at <ProjectDir>/.env): an IP address,
// inside PORTCULLIS_PROXY_SUBNET when that is set. Absent, unparsable or
// outside the subnet = "" (not written; logged).
func (h *Hub) gateIP() string {
	core := readEnvRaw(filepath.Join(h.cfg.ProjectDir, ".env"))
	raw := core[templates.VarMCPGateIP]
	if raw == "" {
		return ""
	}
	ip, err := netip.ParseAddr(raw)
	if err != nil {
		log.Printf("ai: the core env's %s %s is not an IP address: not written", templates.VarMCPGateIP, clipQuoted(raw))
		return ""
	}
	if sub := core["PORTCULLIS_PROXY_SUBNET"]; sub != "" {
		p, err := netip.ParsePrefix(sub)
		if err != nil || !p.Contains(ip) {
			log.Printf("ai: the core env's %s %s is not inside PORTCULLIS_PROXY_SUBNET %s: not written", templates.VarMCPGateIP, ip, clipQuoted(sub))
			return ""
		}
	}
	return ip.String()
}

// clientFinder is the IdP's optional client lookup (keycloak.Client): does
// a client with that clientId exist, and whose is it (its owner tag, ""
// untagged)? adoptTemplateEnvAdditions uses it to never rotate a client's
// secret under the app's running containers (review N2, R1, R5).
type clientFinder interface {
	ClientOwner(ctx context.Context, clientID string) (exists bool, owner string, err error)
}

// pendingEnv is the pending file (JSON, 0600): the values a template
// update added, and for each one the client id it was kept for (review
// R2: a kept value is "ours" only for that same client).
type pendingEnv struct {
	Values  map[string]string `json:"values"`
	Clients map[string]string `json:"clients,omitempty"`
}

// readPendingEnv reads path (missing or unreadable: none; a bad file is
// logged and ignored — the values are generated again).
func readPendingEnv(path string) pendingEnv {
	p := pendingEnv{Values: map[string]string{}, Clients: map[string]string{}}
	b, err := os.ReadFile(path)
	if err != nil {
		return p
	}
	var got pendingEnv
	if err := json.Unmarshal(b, &got); err != nil {
		log.Printf("env: %s is unreadable, ignored: %v", path, err)
		return p
	}
	for k, v := range got.Values {
		p.Values[k] = v
	}
	for k, v := range got.Clients {
		p.Clients[k] = v
	}
	return p
}

// pendingEnvPath is where a start keeps the values a template update
// added while it registers their Keycloak clients (0600, like the .env):
// a start that dies before the .env write reuses them, so a client it
// registered is reconciled with the same secret (review N1).
func (h *Hub) pendingEnvPath(id string) string { return h.envPath(id) + ".pending" }

// adoptTemplateEnvAdditions brings a template update to an instance whose
// .env already exists (contract §2, "Template updates"), before anything
// starts:
//
//  1. every manifest env entry the .env lacks gets a value in memory (a
//     generate: random one a fresh one — or the one an unfinished
//     earlier start kept in the pending file for the same client —, any
//     other "");
//  2. each Keycloak client whose secret_env is one of them is registered
//     with exactly that value (the AI page's ai_client through its own
//     path; one with no generated value is skipped, unhealthy as at
//     enable) and the instance's access role ensured;
//  3. only then are the values written to the .env (and the pending file
//     removed).
//
// Between 1 and 3 the values are kept in the pending file (JSON, 0600:
// each value with the client id it is for), so a crash after a
// registration and before the write reuses them at the next start: the
// registration is repeated with the same secret (idempotent). The .env
// never holds a secret Keycloak wasn't given, and no failure needs an
// undo: the start is refused (409 a client another owner holds, 502
// otherwise; a Stop stays a Stop) and the next one retries with the same
// values.
//
// A client that already exists in Keycloak, tagged with this instance or
// untagged (what RegisterClient would reconcile), and that no unfinished
// earlier start kept a value for (its secret_env renamed by the update)
// is rotated only when none of the app's containers may run
// (projectMayRun: only exited / dead — and created outside Kubernetes —
// count as down; any other or unknown state, or an engine that can't
// answer, counts as running): a stop-then-start or a start of a stopped
// app rotates it, a restart or drift apply over running containers is
// refused 409 before anything is registered or written. Without Keycloak
// the values are written, as at enable. Outside mu (it takes it); the
// caller holds the instance's app lock.
func (h *Hub) adoptTemplateEnvAdditions(ctx context.Context, t *templates.Template) error {
	h.mu.Lock()
	live := t
	if l := h.findLocked(t.ID); l != nil {
		c := *l
		live = &c
	}
	path, pend := h.envPath(live.ID), h.pendingEnvPath(live.ID)
	if _, err := os.Stat(path); err != nil {
		h.mu.Unlock()
		return nil // not generated yet: enable writes it whole
	}
	cur := readEnvRaw(path)
	pk := readPendingEnv(pend)
	kept := pk.Values
	added := map[string]string{}
	for _, v := range live.Manifest.Env {
		if _, ok := cur[v.Key]; ok {
			continue
		}
		val, ok := kept[v.Key]
		if !ok && v.Generate == "random" {
			s, err := randomSecret()
			if err != nil {
				h.mu.Unlock()
				return err
			}
			val = s
		}
		added[v.Key] = val
	}
	if len(added) == 0 {
		// Written by an earlier start that died before removing its file.
		os.Remove(pend)
		h.mu.Unlock()
		return nil
	}
	keys := slices.Sorted(maps.Keys(added))
	var regs []templates.KeycloakClient
	for _, c := range live.Manifest.Clients {
		if c.SecretEnv != "" {
			if _, ok := added[c.SecretEnv]; ok {
				regs = append(regs, c)
			}
		}
	}
	if len(regs) == 0 || h.idp == nil {
		err := setEnvVars(path, added, false)
		if err == nil {
			os.Remove(pend)
		}
		h.mu.Unlock()
		if err != nil {
			return statusErr(500, "writing the variables the template added: %v", err)
		}
		log.Printf("instance %s: the template added %s: written to its .env", live.ID, strings.Join(keys, ", "))
		return nil
	}
	h.mu.Unlock()
	// An existing client of this instance whose secret would change (its
	// secret_env renamed; N2, R1): rotated only while none of the app's
	// containers runs — the engine says so (an unknown answer counts as
	// running: fail closed) —, else refused before anything is registered
	// or written. A stop-then-start (a backup, a move, a delete's undo, a
	// folder reassign, a mail void or resume) or a start of a stopped app
	// rotates it; a restart or a drift apply over running containers is
	// refused. Another owner's client (R5): RegisterClient's conflict
	// answers.
	if f, ok := h.idp.(clientFinder); ok {
		var running *bool
		for _, c := range regs {
			if c.AIClient && added[c.SecretEnv] == "" {
				continue // never registered here (S4): nothing would rotate
			}
			exists, owner, err := f.ClientOwner(ctx, c.ClientID)
			if err != nil {
				return &StatusError{Status: 502, Err: fmt.Errorf("%s was not started: looking up Keycloak client %s, which the template gives a new secret variable: %w", live.ID, c.ClientID, err)}
			}
			if !exists || (owner != live.ID && owner != "") || pk.Clients[c.SecretEnv] == c.ClientID {
				// Missing (a new client), another owner's (RegisterClient's
				// conflict answers, R5) or one this update already kept a
				// value for. An untagged one is what RegisterClient would
				// adopt and reconcile: checked like ours (S1).
				continue
			}
			if running == nil {
				r, rerr := h.projectMayRun(ctx, live.ID)
				if rerr != nil {
					if cerr := ctx.Err(); cerr != nil {
						return fmt.Errorf("checking whether %s runs: %w", live.ID, cerr)
					}
					log.Printf("instance %s: can't tell whether its containers run (%v): treated as running", live.ID, rerr)
					r = true
				}
				running = &r
			}
			if *running {
				return statusErr(409, "%s was not started: the template gives its existing Keycloak client %s a new secret variable %s; registering it now would change the client's secret in Keycloak while the running app still uses the old one — stop the app (or disable and enable %s) to apply the change", live.ID, c.ClientID, c.SecretEnv, live.ID)
			}
			log.Printf("instance %s: the template gives Keycloak client %s a new secret variable %s: its containers are down, so it is rotated before the start", live.ID, c.ClientID, c.SecretEnv)
		}
	}
	// The values survive a crash from here on (reused at the next start),
	// each one marked with the client it is for.
	pk = pendingEnv{Values: added, Clients: map[string]string{}}
	for _, c := range regs {
		pk.Clients[c.SecretEnv] = c.ClientID
	}
	h.mu.Lock()
	err := writePendingEnv(pend, pk)
	h.mu.Unlock()
	if err != nil {
		return statusErr(500, "keeping the variables the template added: %v", err)
	}
	var names []string
	for _, c := range regs {
		secret := added[c.SecretEnv]
		if c.AIClient {
			if secret == "" {
				// A confidential ai_client needs a secret (R3): without a
				// generated one it is left as an enable leaves it,
				// unhealthy until its variable has a value.
				log.Printf("instance %s: the template added ai_client %s with %s, which has no generated value: not registered (unhealthy until it has one)", live.ID, c.ClientID, c.SecretEnv)
				continue
			}
			_, err = h.ensureInstanceAIClientSecret(ctx, live, secret)
		} else {
			spec := h.clientSpec(live, c)
			spec.Secret = secret
			_, err = h.idp.RegisterClient(ctx, spec)
		}
		var conflict *keycloak.ConflictError
		switch {
		case errors.As(err, &conflict):
			return &StatusError{Status: 409, Err: fmt.Errorf("%s was not started: the template added Keycloak client %s, which isn't this instance's: %w", live.ID, c.ClientID, err)}
		case err != nil:
			return &StatusError{Status: 502, Err: fmt.Errorf("%s was not started: the template added Keycloak client %s and registering it failed (starting again retries with the same values): %w", live.ID, c.ClientID, err)}
		}
		names = append(names, c.ClientID)
	}
	if err := h.ensureAccess(ctx, live); err != nil {
		return &StatusError{Status: 502, Err: fmt.Errorf("%s was not started: the access role of the Keycloak clients the template added: %w", live.ID, err)}
	}
	if h.testHookAdoptRegistered != nil {
		if err := h.testHookAdoptRegistered(live.ID); err != nil {
			return err // a simulated crash: registered, not written
		}
	}
	h.mu.Lock()
	// Only what is still missing (nothing else writes these keys, but a
	// value already there always wins).
	now := readEnvRaw(path)
	for k := range added {
		if _, ok := now[k]; ok {
			delete(added, k)
		}
	}
	err = setEnvVars(path, added, false)
	if err == nil {
		os.Remove(pend)
	}
	h.mu.Unlock()
	if err != nil {
		return statusErr(500, "writing the variables the template added (their clients are registered; starting again finishes it): %v", err)
	}
	log.Printf("instance %s: the template added %s: Keycloak clients %s registered, then written to its .env", live.ID, strings.Join(keys, ", "), strings.Join(names, ", "))
	return nil
}

// writePendingEnv writes the pending file (JSON, 0600, atomic).
func writePendingEnv(path string, p pendingEnv) error {
	b, err := json.Marshal(p)
	if err != nil {
		return err
	}
	return fsutil.WriteFileAtomic(path, append(b, '\n'), 0600)
}

// projectMayRun reports whether any container of id's project may be
// running (the rename rotation's check, review S2): only "exited" and
// "dead" — and "created" for a Docker or Podman container that never
// started — count as down; every other or unknown state counts as
// running (Kubernetes' "created" is a starting pod; a placed instance's
// worker runtime isn't known here, so its "created" counts too). A pod or
// container that is gone isn't listed.
func (h *Hub) projectMayRun(ctx context.Context, id string) (bool, error) {
	cs, err := h.rtOf(id).List(ctx, runtime.Filter{Instance: id})
	if err != nil {
		return false, err
	}
	createdIsDown := !h.kubeOn() && h.serverOf(id) == ""
	for _, c := range cs {
		if c.Project != projectName(id) {
			continue
		}
		switch c.State {
		case "exited", "dead":
			continue
		case "created":
			if createdIsDown {
				continue
			}
		}
		return true, nil
	}
	return false, nil
}
