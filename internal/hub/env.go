// randomSecret returns 32 hex characters.
func randomSecret() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// generateAppEnvLocked writes the per-app .env: existing values are kept,
// missing manifest env vars are generated, the instance options' env
// deliveries are written from state (optionEnvLocked: every option env
// name, empty when unset), and ${VAR} references in compose.yml are
// filled from the core .env. Caller must hold mu.
func (h *Hub) generateAppEnvLocked(t *templates.Template, m *directory.Membership) error {
	envFile := h.envPath(t.ID)
	vars := readEnvRaw(envFile) // preserve user edits, as written
	vars["PORTCULLIS_DOMAIN"] = h.cfg.Domain

	for _, v := range t.Manifest.Env {
		if _, exists := vars[v.Key]; exists {
			continue
		}
		switch v.Generate {
		case "random":
			s, err := randomSecret()
			if err != nil {
				return err
			}
			vars[v.Key] = s
		default:
			vars[v.Key] = ""
		}
	}
	for k, v := range h.portEnvLocked(t) {
		vars[k] = v
	}
	optEnv, err := h.optionEnvLocked(t, m)
	if err != nil {
		return err
	}
	for k, v := range optEnv {
		vars[k] = v
	}
	// The instance variables (contract §2, §3.1) are derived, never kept
	// from an earlier file: hostnames and names follow the instance.
	for k, v := range t.InstanceEnv {
		vars[k] = v
	}
	for k, v := range h.aiEnvLocked(t) {
		vars[k] = v
	}
	// The model provider variables (§15.12, Task 23): exactly an AI page's
	// selected, set secrets (single-quoted); never a stale or foreign one.
	provEnv, err := h.providerEnvLocked(t)
	if err != nil {
		return err
	}
	for k := range vars {
		if strings.HasPrefix(k, ProviderVarPrefix) {
			delete(vars, k)
		}
	}
	for k, v := range provEnv {
		vars[k] = v
	}
	coreEnv := readEnvRaw(filepath.Join(h.cfg.ProjectDir, ".env"))
	for ref := range templates.EnvRefs(string(t.ReadCompose())) {
		if _, exists := vars[ref]; !exists {
			if v, ok := coreEnv[ref]; ok {
				vars[ref] = v
			}
		}
	}

	lines := []string{
		"# Auto-generated by Portcullis Hub — do not edit manually",
		fmt.Sprintf("# App: %s", t.Manifest.Name),
	}
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		_, quoted := optEnv[k]
		_, prov := provEnv[k]
		lines = append(lines, envLine(k, vars[k], quoted || prov))
	}
	// 0600: contains generated secrets.
	return fsutil.WriteFileAtomic(envFile, []byte(strings.Join(lines, "\n")+"\n"), 0600)
}

// writeOptionEnvLocked updates the option variables (optionEnvLocked,
// single-quoted) and the port variables (portEnvLocked) in id's .env,
// keeping every other line. Caller must hold mu.
func (h *Hub) writeOptionEnvLocked(t *templates.Template, m *directory.Membership) error {
	vars, err := h.optionEnvLocked(t, m)
	if err != nil {
		return err
	}
	if err := setEnvVars(h.envPath(t.ID), h.portEnvLocked(t), false); err != nil {
		return err
	}
	return setEnvVars(h.envPath(t.ID), vars, true)
}

// portEnvLocked are t's port settings as env variables: the stored port
// keys and <KEY>_BIND as they are, and the effective value of every port
// the app binds itself (network_mode: host, ranges: compose publishes
// nothing for them, the template reads them from the env). Caller must
// hold mu.
func (h *Hub) portEnvLocked(t *templates.Template) map[string]string {
	s := h.st.Settings[t.ID]
	out := maps.Clone(s.Ports)
	if out == nil {
		out = map[string]string{}
	}
	for k, v := range hostNetPortValues(t, s.Ports) {
		out[k] = v
	}
	return out
}

// optionEnvLocked is what the Hub writes for t's options into its .env
// (unquoted values; the writers single-quote them): every env name of an
// instance option, rendered per delivery (RenderDelivery; an indexed
// NAME_{n} one item per variable, unused ones empty), empty when the
// option has no value. A secret option's value comes from the secrets
// store (empty when unset or cleared). Left alone (P12): group-scope
// options (their records) and person-entered lists (the delivery engine
// writes those outside mu). A stored value one env delivery can't carry
// (a template update added the delivery; save refuses such values) fails
// closed for that delivery's variables only: written empty, logged and
// reported in the panel's deliveries (unit env:values); the error is
// only the secrets store being unreadable. Errors and problems never
// carry a value. The shared-folder variables (folderEnvLocked) come
// last. Caller must hold mu.
func (h *Hub) optionEnvIn(rv renderView, t *templates.Template, m *directory.Membership) (map[string]string, []string, error) {
	s := rv.settings[t.ID]
	out := map[string]string{}
	var problems []string
	var secrets map[string]string
	opts := t.Manifest.Options()
	put := func(o *templates.Option, redact []string, render func(d *templates.Delivery) (map[string]string, error)) {
		for _, d := range envDeliveries(o) {
			env, err := render(&d)
			if err != nil {
				for _, n := range envDeliveryNames(o, &d) {
					out[n] = ""
				}
				problems = append(problems, fmt.Sprintf("setting %s: %s: written empty", o.Key, redactValues(err.Error(), redact)))
				continue
			}
			for k, x := range env {
				out[k] = x
			}
		}
	}
	for i := range opts {
		o := &opts[i]
		if o.EffectiveScope() == templates.ScopeGroup && len(envDeliveries(o)) > 0 {
			// The records as one JSON value per env delivery: only
			// records of the stored type whose group id matches the
			// caller's directory snapshot m (fetched outside mu); no
			// snapshot = no records (fail closed).
			var recs []settings.Row
			if h.typeMatchesLocked(t, o.Key, o) {
				recs = h.groupRecordsOut(t, o, s.Groups[o.Key], m)
			}
			put(o, nil, func(d *templates.Delivery) (map[string]string, error) {
				return renderGroupEnvDelivery(o, recs, d)
			})
			continue
		}
		if o.EffectiveScope() != templates.ScopeInstance {
			continue
		}
		if o.Type == templates.TypeSecret {
			if len(envDeliveries(o)) == 0 {
				continue
			}
			if secrets == nil {
				var err error
				if secrets, err = h.secretValues(t.ID); err != nil {
					return nil, nil, err
				}
			}
			var v any
			if x := secrets[o.Key]; x != "" {
				if _, set := s.Secrets[o.Key]; set {
					v = x
				}
			}
			put(o, []string{secrets[o.Key]}, func(d *templates.Delivery) (map[string]string, error) {
				return renderEnvDelivery(o, v, d)
			})
			continue
		}
		v, ok := h.effectiveValue(t, o, s)
		if !ok {
			v = nil
		}
		if str, isStr := v.(string); isStr && o.Type == templates.TypePath && strings.HasPrefix(str, folderPrefix) {
			// A folder value's env delivery carries its host path (the
			// kind never resolves a ref).
			if host, err := folderHostPath(h.folders, str); err == nil {
				v = host
			} else {
				v = nil
			}
		}
		put(o, nil, func(d *templates.Delivery) (map[string]string, error) {
			return renderEnvDelivery(o, v, d)
		})
	}
	// A gid reference holding a folder group's gid no assignment wrote
	// (ruling 30) is written empty: such a gid would reach the app.
	for _, key := range h.gidRangeProblemsIn(rv, t, s) {
		o := optionByKey(t, key)
		for _, n := range o.EnvNames() {
			out[n] = ""
		}
		problems = append(problems, fmt.Sprintf("setting %s: %s: written empty", key, errGIDReserved))
	}
	// Last (ruling 11): the folder variables, and a gid_env join's
	// variable set to the folder gid over the option's own value.
	for k, v := range h.folderEnvIn(rv, t) {
		out[k] = v
	}
	// The Local networks (F35, §3.1): every .env write carries them, the
	// canonical prefixes comma-joined ('' = saved empty: loopback only).
	out[templates.VarLocalNetworks] = h.localNetworksEnvLocked()
	// The setup choices' compose profiles (§13.18): Hub-set, every .env
	// write of a template with profiled services carries them ('' =
	// none). A template without any has nothing a profile could start:
	// its .env stays as it was (a manifest can't declare the variable).
	if len(t.ProfiledServices) > 0 {
		out[templates.VarComposeProfiles] = h.composeProfilesEnv(t, s)
	}
	return out, problems, nil
}

// localNetworksEnvLocked is PORTCULLIS_LOCAL_NETWORKS' value. Caller
// holds mu (read).
func (h *Hub) localNetworksEnvLocked() string {
	nets := h.localNetworksLocked()
	parts := make([]string, len(nets))
	for i, p := range nets {
		parts[i] = p.String()
	}
	return strings.Join(parts, ",")
}

// optionEnvLocked is optionEnvIn over the Hub's state; its problems are
// recorded for the panel (setEnvProblems). Caller must hold mu.
func (h *Hub) optionEnvLocked(t *templates.Template, m *directory.Membership) (map[string]string, error) {
	out, problems, err := h.optionEnvIn(h.liveView(), t, m)
	if err != nil {
		return nil, err
	}
	h.setEnvProblems(t.ID, problems)
	return out, nil
}

// envDeliveryNames are the variables env delivery d of o writes (an
// indexed NAME_{n}: each NAME_<i>).
func envDeliveryNames(o *templates.Option, d *templates.Delivery) []string {
	prefix, ok := strings.CutSuffix(d.Env, templates.IndexSuffix)
	if !ok {
		return []string{d.Env}
	}
	var out []string
	for _, n := range o.EnvNames() {
		if strings.HasPrefix(n, prefix+"_") {
			out = append(out, n)
		}
	}
	return out
}

// setEnvProblems records instance id's option env values written empty
// (optionEnvLocked), logging each new one once.
func (h *Hub) setEnvProblems(id string, problems []string) {
	sort.Strings(problems)
	h.envProblemsMu.Lock()
	defer h.envProblemsMu.Unlock()
	prev := h.envProblems[id]
	if strings.Join(prev, "\n") == strings.Join(problems, "\n") {
		return
	}
	for _, p := range problems {
		if !slices.Contains(prev, p) {
			log.Printf("settings: %s: WARNING: %s (the value can't go in the .env)", id, p)
		}
	}
	if h.envProblems == nil {
		h.envProblems = map[string][]string{}
	}
	if len(problems) == 0 {
		delete(h.envProblems, id)
		return
	}
	h.envProblems[id] = problems
}

// envProblemsUnit is the env:values unit the panel shows while some
// option env value is written empty (ok: there is one).
func (h *Hub) envProblemsUnit(id string) (UnitResult, bool) {
	h.envProblemsMu.Lock()
	defer h.envProblemsMu.Unlock()
	p := h.envProblems[id]
	if len(p) == 0 {
		return UnitResult{}, false
	}
	return UnitResult{Unit: unitEnvValues, Error: clipRunes(strings.Join(p, "; "), unitErrorMax)}, true
}

// envDeliveries are o's env deliveries: the declared ones, or the
// implicit env UPPER(key) of an instance option without deliveries.
func envDeliveries(o *templates.Option) []templates.Delivery {
	if len(o.Delivery) == 0 {
		if n := o.EnvName(); n != "" {
			return []templates.Delivery{{Env: n}}
		}
		return nil
	}
	var out []templates.Delivery
	for _, d := range o.Delivery {
		if d.Env != "" {
			out = append(out, d)
		}
	}
	return out
}

// renderOptionEnv renders the canonical v (nil = no value: every name
// empty) for each of o's env deliveries. A rendered value env can't
// carry single-quoted (a ' or a newline) is an error naming the variable.
func renderOptionEnv(o *templates.Option, v any) (map[string]string, error) {
	out := map[string]string{}
	for _, d := range envDeliveries(o) {
		env, err := renderEnvDelivery(o, v, &d)
		if err != nil {
			return nil, err
		}
		for k, x := range env {
			out[k] = x
		}
	}
	return out, nil
}

// renderEnvDelivery is renderOptionEnv for one env delivery d.
func renderEnvDelivery(o *templates.Option, v any, d *templates.Delivery) (map[string]string, error) {
	out := map[string]string{}
	if prefix, ok := strings.CutSuffix(d.Env, templates.IndexSuffix); ok {
		var items []string
		if v != nil {
			var err error
			if items, err = settings.RenderIndexed(o, v, d); err != nil {
				return nil, err
			}
		}
		for _, n := range o.EnvNames() {
			if !strings.HasPrefix(n, prefix+"_") {
				continue
			}
			i, _ := strconv.Atoi(strings.TrimPrefix(n, prefix+"_"))
			x := ""
			if i >= 1 && i <= len(items) {
				x = items[i-1]
			}
			if _, err := envQuote(x); err != nil {
				return nil, fmt.Errorf("env %s: %w", n, err)
			}
			out[n] = x
		}
		return out, nil
	}
	x := ""
	if v != nil {
		r, err := settings.RenderDelivery(o, v, d)
		if err != nil {
			return nil, err
		}
		x = r.Text
	}
	if err := settings.CheckEnvText(x, settings.EnvJSON(o, d)); err != nil {
		return nil, fmt.Errorf("env %s: %w", d.Env, err)
	}
	out[d.Env] = x
	return out, nil
}

// envQuote single-quotes v for an .env file: compose reads a
// single-quoted value literally ($, #, spaces and " stay as they are). A
// value with ', a backslash (compose's dotenv reads \' inside single
// quotes as an escaped quote: a trailing \ would swallow the next line)
// or a line break can't be single-quoted safely: an error.
func envQuote(v string) (string, error) {
	if err := settings.CheckEnvText(v, false); err != nil {
		return "", err
	}
	return "'" + v + "'", nil
}

// envLine is one KEY=VALUE line. A Hub-written option value (quote) is
// single-quoted (envQuote, contract §13.5; empty is KEY=); any other
// value is raw text written exactly as given — what compose reads from
// it (inline comments, $$, double quotes, interpolation) is unchanged.
// An option value that can't be quoted never reaches here (refused at
// save); it is written empty rather than unquoted.
func envLine(k, v string, quote bool) string {
	if !quote || v == "" {
		return k + "=" + v
	}
	q, err := envQuote(v)
	if err != nil {
		return k + "="
	}
	return k + "=" + q
}

// envUnquote is a value as the Hub reads it: the content of a value the
// Hub single-quoted (no ' or \ inside), anything else as written.
func envUnquote(v string) string {
	if len(v) >= 2 && v[0] == '\'' && v[len(v)-1] == '\'' && !strings.ContainsAny(v[1:len(v)-1], "'\\") {
		return v[1 : len(v)-1]
	}
	return v
}

// readEnvFile parses KEY=VALUE lines (missing file = empty map); values
// the Hub single-quoted are unquoted (envUnquote).
func readEnvFile(path string) map[string]string {
	out := readEnvRaw(path)
	for k, v := range out {
		out[k] = envUnquote(v)
	}
	return out
}

// readEnvRaw is readEnvFile with every value's raw text (what writers
// write back unchanged).
func readEnvRaw(path string) map[string]string {
	data, err := os.ReadFile(path)
	if err != nil {
		return map[string]string{}
	}
	return parseEnvRaw(data)
}

// parseEnv parses KEY=VALUE lines, unquoting values the Hub
// single-quoted.
func parseEnv(data []byte) map[string]string {
	out := parseEnvRaw(data)
	for k, v := range out {
		out[k] = envUnquote(v)
	}
	return out
}

// parseEnvRaw parses KEY=VALUE lines, values as written.
func parseEnvRaw(data []byte) map[string]string {
	result := make(map[string]string)
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, v, ok := strings.Cut(line, "="); ok {
			result[k] = v
		}
	}
	return result
}

// writeEnvMap writes vars (raw text) as a sorted KEY=VALUE file (0600:
// secrets).
func writeEnvMap(path string, vars map[string]string) error {
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("# Auto-generated by Portcullis Hub — do not edit manually\n")
	for _, k := range keys {
		b.WriteString(envLine(k, vars[k], false) + "\n")
	}
	return fsutil.WriteFileAtomic(path, []byte(b.String()), 0600)
}

// setEnvVar updates or appends key=value (raw text) in an .env file.
func setEnvVar(envFile, key, value string) error {
	return setEnvVars(envFile, map[string]string{key: value}, false)
}

// setEnvVars updates or appends each key=value (envLine; quote: Hub
// option values, single-quoted; else raw text) in an .env file in one
// write, keeping every other line as it is; new keys are appended
// sorted.
func setEnvVars(envFile string, vars map[string]string, quote bool) error {
	if len(vars) == 0 {
		return nil
	}
	data, err := os.ReadFile(envFile)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	var lines []string
	if len(data) > 0 {
		lines = strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
	}
	done := map[string]bool{}
	for i, line := range lines {
		k, _, ok := strings.Cut(strings.TrimSpace(line), "=")
		if !ok || strings.HasPrefix(k, "#") {
			continue
		}
		// Every line of a duplicated key (compose reads the last one).
		if v, want := vars[k]; want {
			lines[i] = envLine(k, v, quote)
			done[k] = true
		}
	}
	keys := make([]string, 0, len(vars))
	for k := range vars {
		if !done[k] {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	for _, k := range keys {
		lines = append(lines, envLine(k, vars[k], quote))
	}
	return fsutil.WriteFileAtomic(envFile, []byte(strings.Join(lines, "\n")+"\n"), 0600)
}

// hostNetPortValues are the effective values of the ports an app binds
// itself (network_mode: host or a range): compose publishes nothing for
// them, the template reads them from the env.
func hostNetPortValues(t *templates.Template, values map[string]string) map[string]string {
	out := map[string]string{}
	for _, p := range t.Manifest.Ports {
		if !p.NetworkModeHost && p.Range == "" {
			continue
		}
		v, ok := values[p.Key]
		switch {
		case ok && v != "":
			out[p.Key] = v
		case ok && !p.Required:
			out[p.Key] = ""
		case p.Range != "":
			out[p.Key] = p.Range
		case p.Default > 0:
			out[p.Key] = fmt.Sprint(p.Default)
		}
	}
	return out
}

// refreshInstanceEnvLocked rewrites the derived variables (domain and
// instance variables) and the settings' variables (optionEnvLocked) in
// an existing .env before every compose up, so the routed hostnames are
// always the Hub's and the app starts with the stored settings. Caller
// must hold mu.
func (h *Hub) refreshInstanceEnvLocked(t *templates.Template, m *directory.Membership) error {
	path := h.envPath(t.ID)
	if _, err := os.Stat(path); err != nil {
		return nil // not generated yet: enable writes it whole
	}
	cur := readEnvRaw(path)
	opts, err := h.optionEnvLocked(t, m)
	if err != nil {
		return err
	}
	want := h.portEnvLocked(t)
	want["PORTCULLIS_DOMAIN"] = h.cfg.Domain
	for k, v := range t.InstanceEnv {
		want[k] = v
	}
	for k, v := range h.aiEnvLocked(t) {
		want[k] = v
	}
	for k, v := range want {
		if c, ok := cur[k]; ok && c == v {
			delete(want, k)
		}
	}
	for k, v := range opts {
		if c, ok := cur[k]; ok && strings.TrimPrefix(envLine(k, v, true), k+"=") == c {
			delete(opts, k)
		}
	}
	if err := setEnvVars(path, want, false); err != nil {
		return err
	}
	if err := setEnvVars(path, opts, true); err != nil {
		return err
	}
	// The model provider variables of the instance's own selection (a
	// restore rewrites them from the store: G30(b)).
	return h.syncProviderEnvLocked(t)
}

// aiEnvLocked are the AI variables of an ai.mcp template's instance
// (contract §3.1, G42): PORTCULLIS_AI_ENABLED true while one of its
// companions is switched on (one owing a revoke_all counts as off),
// PORTCULLIS_AI_READONLY_<C> true unless C is on in read_write — all off
// while the master switch is off or the effective policy is at LoA 3
// (aiOnLocked) —, and
// core's PORTCULLIS_MCP_GATE_IP (gateIPLocked). nil for every other
// template. Caller holds mu.
func (h *Hub) aiEnvLocked(t *templates.Template) map[string]string {
	if !t.HasAIMCP() {
		return nil
	}
	sw := h.st.AIInstances[t.ID].Companions
	out := map[string]string{templates.VarAIEnabled: "false"}
	// Master switch off or LoA 3: off in the app too (12b), whatever the
	// companions' switches say.
	on := h.aiOnLocked(t)
	for _, c := range t.Manifest.AI.MCP {
		s := sw[c.Name]
		ro := "true"
		if on && s.Enabled && !s.RevokePending {
			out[templates.VarAIEnabled] = "true"
			if s.Mode == templates.AIReadWrite {
				ro = "false"
			}
		}
		out[templates.ReadOnlyVar(c.Name)] = ro
	}
	if ip := h.gateIP(); ip != "" {
		out[templates.VarMCPGateIP] = ip
	}
	return out
}

// gateIP is core's PORTCULLIS_MCP_GATE_IP from the core env subset the
// Hub reads (secrets/hub/core.env at <ProjectDir>/.env): an IP address,
// inside PORTCULLIS_PROXY_SUBNET when that is set. Absent, unparsable or
// outside the subnet = "" (not written; logged).
func (h *Hub) gateIP() string {
	core := readEnvRaw(filepath.Join(h.cfg.ProjectDir, ".env"))
	raw := core[templates.VarMCPGateIP]
	if raw == "" {
		return ""
	}
	ip, err := netip.ParseAddr(raw)
	if err != nil {
		log.Printf("ai: the core env's %s %s is not an IP address: not written", templates.VarMCPGateIP, clipQuoted(raw))
		return ""
	}
	if sub := core["PORTCULLIS_PROXY_SUBNET"]; sub != "" {
		p, err := netip.ParsePrefix(sub)
		if err != nil || !p.Contains(ip) {
			log.Printf("ai: the core env's %s %s is not inside PORTCULLIS_PROXY_SUBNET %s: not written", templates.VarMCPGateIP, ip, clipQuoted(sub))
			return ""
		}
	}
	return ip.String()
}
