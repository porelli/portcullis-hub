package hub

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/portcullis/hub/internal/fsutil"
	"github.com/portcullis/hub/internal/templates"
)

// randomSecret returns 32 hex characters.
func randomSecret() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// generateAppEnvLocked writes the per-app .env: existing values are kept,
// missing manifest env vars are generated, user settings are applied, and
// ${VAR} references in compose.yml are filled from the core .env.
// Caller must hold mu.
func (h *Hub) generateAppEnvLocked(t *templates.Template) error {
	envFile := h.envPath(t.ID)
	vars := readEnvFile(envFile) // preserve user edits
	vars["PORTCULLIS_DOMAIN"] = h.cfg.Domain

	for _, v := range t.Manifest.Env {
		if _, exists := vars[v.Key]; exists {
			continue
		}
		switch v.Generate {
		case "random":
			s, err := randomSecret()
			if err != nil {
				return err
			}
			vars[v.Key] = s
		default:
			vars[v.Key] = ""
		}
	}
	for k, v := range h.st.Settings[t.ID] {
		vars[k] = v
	}
	coreEnv := readEnvFile(filepath.Join(h.cfg.ProjectDir, ".env"))
	for ref := range templates.EnvRefs(string(t.ReadCompose())) {
		if _, exists := vars[ref]; !exists {
			if v, ok := coreEnv[ref]; ok {
				vars[ref] = v
			}
		}
	}

	lines := []string{
		"# Auto-generated by Portcullis Hub — do not edit manually",
		fmt.Sprintf("# App: %s", t.Manifest.Name),
	}
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		lines = append(lines, k+"="+vars[k])
	}
	// 0600: contains generated secrets.
	return fsutil.WriteFileAtomic(envFile, []byte(strings.Join(lines, "\n")+"\n"), 0600)
}

// readEnvFile parses KEY=VALUE lines (missing file = empty map).
func readEnvFile(path string) map[string]string {
	result := make(map[string]string)
	data, err := os.ReadFile(path)
	if err != nil {
		return result
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, v, ok := strings.Cut(line, "="); ok {
			result[k] = v
		}
	}
	return result
}

// setEnvVar updates or appends key=value in an .env file.
func setEnvVar(envFile, key, value string) error {
	data, err := os.ReadFile(envFile)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	lines := strings.Split(string(data), "\n")
	found := false
	for i, line := range lines {
		if strings.HasPrefix(line, key+"=") {
			lines[i] = key + "=" + value
			found = true
			break
		}
	}
	if !found {
		lines = append(lines, key+"="+value)
	}
	return fsutil.WriteFileAtomic(envFile, []byte(strings.Join(lines, "\n")), 0600)
}
